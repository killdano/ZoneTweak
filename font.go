var glyphs = map[rune][7]uint8{}

func init() {
	for r, s := range glyphSrc {
		s = strings.ReplaceAll(s, "_", ".")
		for len(s) < 35 {
			s = strings.Repeat(".", 35-len(s)) + s
		}
		var g [7]uint8
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if s[row*5+col] == '#' {
					g[row] |= 1 << (4 - col)
				}
			}
		}
		glyphs[r] = g
	}
}

func textWidth(s string) int { return len([]rune(s))*6 - 1 }

func drawText(b *batch, s string, origin, right, up vec3, px float64, col rgba) {
	s = strings.ToUpper(s)
	x := 0
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs['?']
		}
		for row := 0; row < 7; row++ {
			for c := 0; c < 5; c++ {
				if g[row]&(1<<(4-c)) == 0 {
					continue
				}
				p := origin.add(right.mul(float64(x+c) * px)).add(up.mul(float64(6-row) * px))
				b.quad(p, p.add(right.mul(px)), p.add(right.mul(px)).add(up.mul(px)), p.add(up.mul(px)), col)
			}
		}
		x += 6
	}
}

func drawTextCentered(b *batch, s string, center, right, up vec3, px float64, col rgba) {
	w := float64(textWidth(s)) * px
	o := center.sub(right.mul(w / 2)).sub(up.mul(3.5 * px))
	drawText(b, s, o, right, up, px, col)
}
